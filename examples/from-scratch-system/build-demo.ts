// ── Step 3: Capture what the agent prompt would receive ──────────────────────

/** Mirror of packages/core/src/agent.ts formatDesignSystem (kept local so this
 *  demo script doesn't import from the bundled-only core package). If the
 *  source ever diverges, update this script and document the drift in
 *  components.added-to-prompt section. */
function formatDesignSystemForPrompt(ds: StoredDesignSystem): string {
  const lines = [
    '## Design system to follow',
    `Root path: ${ds.rootPath}`,
    `Summary: ${ds.summary}`,
  ];
  if (ds.colors.length > 0) lines.push(`Colors: ${ds.colors.join(', ')}`);
  if (ds.fonts.length > 0) lines.push(`Fonts: ${ds.fonts.join(', ')}`);
  if (ds.spacing.length > 0) lines.push(`Spacing: ${ds.spacing.join(', ')}`);
  if (ds.radius.length > 0) lines.push(`Radius: ${ds.radius.join(', ')}`);
  if (ds.shadows.length > 0) lines.push(`Shadows: ${ds.shadows.join(', ')}`);
  if (ds.components && ds.components.length > 0) {
    lines.push('Component rules:');
    for (const c of ds.components) lines.push(`- ${c.name}: ${c.rule}`);
  }
  if (ds.sourceFiles.length > 0) {
    lines.push(`Source files: ${ds.sourceFiles.join(', ')}`);
  }
  return lines.join('\n');
}

const promptFragment = formatDesignSystemForPrompt(aurora);
writeFileSync(join(__dirname, 'PROMPT_FRAGMENT.txt'), promptFragment, 'utf8');

