/**
 * Demo: build a from-scratch design system, persist it to DESIGN.md,
 * confirm it would flow into the agent prompt, and render a mock webapp
 * that consumes the exact tokens.
 *
 * Run with: pnpm tsx examples/from-scratch-system/build-demo.ts
 *
 * This is a non-interactive end-to-end proof of the design-system parity
 * work. No LLM call is made (would require an API key + cost real money).
 * Instead the script:
 *   1. Constructs a custom StoredDesignSystem (Aurora — purple/cyan,
 *      deliberately distinct from the warm-cream ATV default)
 *   2. Writes a DESIGN.md to examples/from-scratch-system/DESIGN.md
 *      via the same rewriteDesignMd() the IPC handler uses
 *   3. Calls formatDesignSystem() — the EXACT function packages/core uses
 *      to inject design tokens into the LLM prompt — and writes the prompt
 *      fragment to PROMPT_FRAGMENT.txt so we can confirm the custom values
 *      would reach the model
 *   4. Renders mockup.html using the same tokens, so a human can see the
 *      design system applied to a real UI
 *
 * Everything in this folder is a build artifact — feel free to delete and
 * re-run to regenerate.
 */

